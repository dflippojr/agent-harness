import { test, expect, expectDone, audit } from './fixtures';
import { randomUUID } from 'node:crypto';

test('AH-11 job toggle, validation, CRUD, run and audit persist', async ({ signedIn: page }) => {
  await page.goto('/#/jobs');
  const toggle = page.getByRole('switch', { name: 'Weekly cleanup enabled', exact: true });
  const wasEnabled = await toggle.isChecked();
  const toggled = page.waitForResponse(r => r.request().method() === 'PUT' && /\/jobs\//.test(r.url()));
  await toggle.setChecked(!wasEnabled);
  expect((await toggled).ok()).toBe(true);
  await page.reload();
  await expect(page.getByRole('switch', { name: 'Weekly cleanup enabled', exact: true })).toBeChecked({ checked: !wasEnabled });
  await page.goto('/#/jobs/new');
  const name = 'UI job ' + randomUUID();
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByLabel('Task', { exact: true }).fill('Write the nightly report.');
  await page.getByLabel('Schedule (tower time)').selectOption('');
  await page.getByLabel('Cron', { exact: true }).fill('bad');
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await expect(page.getByText('a schedule needs 5 fields: minute hour day-of-month month day-of-week', { exact: true }).first()).toBeVisible();
  await expect(page).toHaveURL(/#\/jobs\/new$/);
  await page.getByLabel('Cron', { exact: true }).fill('0 5 * * *');
  await page.getByLabel('Project', { exact: true }).selectOption('ui');
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await expect(page).toHaveURL(/#\/jobs\/j-[^/]+$/);
  const jobUrl = page.url();
  const jobId = jobUrl.split('/').pop()!;
  await page.reload();
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue(name);
  const updated = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().endsWith('/jobs/' + jobId));
  await page.getByLabel('Name', { exact: true }).fill(name + ' v2');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  expect((await updated).ok()).toBe(true);
  await page.reload();
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue(name + ' v2');
  await page.getByRole('button', { name: 'Run now', exact: true }).locator('visible=true').first().click();
  await expect(page).toHaveURL(/#\/s\/[^/]+$/);
  await expectDone(page);
  await expect(page.locator('main')).toContainText('Nightly report written to reports/nightly.md. All quiet.');
  await page.goto(jobUrl);
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.reload();
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue(name + ' v2');
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete job', exact: true }).click();
  await expect(page).toHaveURL(/#\/jobs$/);
  await page.reload();
  await expect(page.locator('.job-row').first()).toBeVisible();
  await expect(page.locator('[data-job="' + jobId + '"]')).toHaveCount(0);
  const handle = await (await page.request.get('/ready')).json();
  const rows = await audit(page, { target_id: jobId });
  for (const action of ['job.create', 'job.update', 'job.run', 'job.delete']) {
    expect(rows).toEqual(expect.arrayContaining([expect.objectContaining({ action, outcome: 'ok', actor_kind: 'owner_key', key_id: handle.key_id })]));
  }
  expect(rows.find(row => row.action === 'job.update' && row.outcome === 'ok').metadata.fields).toEqual(['name']);
});
